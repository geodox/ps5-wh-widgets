'use strict';
// Build one bridge delta per supported firmware, plus the table the payload
// embeds (framework/build.sh picks these up).
//
//   node tools/build_deltas.js [dumps dir] [out dir]     (defaults: dumps out/deltas)
//
// Every tools/fidmaps/fw<NNNN>.json is one supported firmware. Its hub dump is
// found in the dumps dir by the map's source_sha1 (dumps are never committed; see
// scripts/dump_hub.py). Each bridge is built with that map, turned into a delta
// and verified byte-exact (make_delta.js). Outputs, in the out dir:
//   fw<NNNN>.delta   one per firmware
//   deltas.S         .incbin of every delta (wh_delta_fw<NNNN>_start/_end)
//   deltas.h         WH_DELTA_TABLE rows + WH_DELTA_FWS, read by framework/bridge.c
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { buildBridge } = require('./build_bridge_hbc.js');
const { makeDelta } = require('./make_delta.js');

const MAPS = path.join(__dirname, 'fidmaps');
const MIN_CONFIDENCE = 0.9;
const [DUMPS = 'dumps', OUT = path.join('out', 'deltas')] = process.argv.slice(2);

const sha1 = b => crypto.createHash('sha1').update(b).digest('hex');
const dumpBySha = new Map();
for (const f of fs.existsSync(DUMPS) ? fs.readdirSync(DUMPS) : []) {
  if (f.endsWith('.hbc')) dumpBySha.set(sha1(fs.readFileSync(path.join(DUMPS, f))), path.join(DUMPS, f));
}

// A hub module id the loader requires; 0 (= not available, loader falls back to
// its own frame) unless the matcher resolved it confidently.
function moduleId(map, name) {
  const m = (map.modules || []).find(x => x.name === name);
  if (m && Number.isInteger(m.id) && m.confidence >= MIN_CONFIDENCE) return m.id;
  console.warn(`fw${map.fw}: module ${name} unresolved; the loader will use its own frame`);
  return 0;
}

const rows = [];
fs.mkdirSync(OUT, { recursive: true });
for (const f of fs.readdirSync(MAPS).filter(f => /^fw\d{4}\.json$/.test(f)).sort()) {
  const map = JSON.parse(fs.readFileSync(path.join(MAPS, f), 'utf8'));
  const fw = String(map.fw).padStart(4, '0');
  if (f !== `fw${fw}.json`) throw new Error(`${f}: map says fw ${map.fw}`);
  const hub = dumpBySha.get(map.source_sha1);
  if (!hub) throw new Error(`fw${fw}: no hub dump with sha1 ${map.source_sha1} in ${DUMPS}`);
  const src = fs.readFileSync(hub);
  const { blob, ops } = makeDelta(src, buildBridge(hub, map, () => {}));
  fs.writeFileSync(path.join(OUT, `fw${fw}.delta`), blob);
  rows.push({ fw, frame: moduleId(map, 'stockFrame'), header: moduleId(map, 'stockHeader') });
  console.log(`fw${fw}: ${path.basename(hub)} -> fw${fw}.delta ${blob.length} bytes (${ops} ops), verified`);
}
if (!rows.length) throw new Error(`no maps in ${MAPS}`);

const label = fw => `${+fw.slice(0, 2)}.${fw.slice(2)}`;
fs.writeFileSync(path.join(OUT, 'deltas.S'),
  '/* generated by tools/build_deltas.js -- do not edit */\n.section .rodata\n' +
  rows.map(r => `.align 16\n.global wh_delta_fw${r.fw}_start\n.global wh_delta_fw${r.fw}_end\n` +
    `wh_delta_fw${r.fw}_start:\n.incbin "fw${r.fw}.delta"\nwh_delta_fw${r.fw}_end:\n`).join(''));
fs.writeFileSync(path.join(OUT, 'deltas.h'),
  '/* generated by tools/build_deltas.js -- do not edit */\n#ifndef WH_DELTAS_H\n#define WH_DELTAS_H\n#include <stdint.h>\n\n' +
  rows.map(r => `extern const uint8_t wh_delta_fw${r.fw}_start[], wh_delta_fw${r.fw}_end[];\n`).join('') +
  '\n/* { firmware (kernel fw version >> 16), delta start, delta end,\n *   stock frame module id, stock header module id (0 = not available) } */\n' +
  '#define WH_DELTA_TABLE \\\n' +
  rows.map(r => `  { 0x${r.fw}, wh_delta_fw${r.fw}_start, wh_delta_fw${r.fw}_end, ${r.frame}, ${r.header} }`).join(', \\\n') +
  '\n\n' + `#define WH_DELTA_FWS "${rows.map(r => label(r.fw)).join(', ')}"\n\n#endif\n`);
console.log(`wrote ${OUT}/deltas.S, deltas.h (${rows.map(r => label(r.fw)).join(', ')})`);
