'use strict';
// Per-module pages for the hub atlas, generated from hub_index.js output.
//
//   node tools/hub_pages.js [--atlas <dir>] [--ref 1320] [--target 1360]
//
// Reads <atlas>/modules_fw<ref>.json, <atlas>/modules_fw<target>.json and
// <atlas>/xref_<ref>_<target>.json (defaults: dumps/hub-atlas, 1320, 1360) and writes
// <atlas>/modules/<id>.md for every ref module, plus <atlas>/modules/INDEX.md.
// Hand-written notes live in <atlas>/notes/<id>.md and are inlined; they are never
// overwritten, so regeneration keeps them. Output is Sony-derived: dumps/ only.
const fs = require('fs');
const path = require('path');

function main() {
  const argv = process.argv.slice(2);
  const opt = (n, d) => { const i = argv.indexOf(n); return i < 0 ? d : argv[i + 1]; };
  const atlas = path.resolve(opt('--atlas', path.join(__dirname, '..', 'dumps', 'hub-atlas')));
  const ref = opt('--ref', '1320'), tgt = opt('--target', '1360');
  const A = JSON.parse(fs.readFileSync(path.join(atlas, `modules_fw${ref}.json`), 'utf8'));
  const B = JSON.parse(fs.readFileSync(path.join(atlas, `modules_fw${tgt}.json`), 'utf8'));
  const X = JSON.parse(fs.readFileSync(path.join(atlas, `xref_${ref}_${tgt}.json`), 'utf8'));
  const byB = new Map(B.modules.map(r => [r.id, r]));
  const importers = new Map();
  for (const r of A.modules) for (const d of r.requires) { if (!importers.has(d)) importers.set(d, []); importers.get(d).push(r.id); }
  const outDir = path.join(atlas, 'modules');
  const notesDir = path.join(atlas, 'notes');
  fs.mkdirSync(outDir, { recursive: true });
  fs.mkdirSync(notesDir, { recursive: true });
  const link = id => `[${id}](${id}.md)`;
  const esc = s => String(s).replace(/\|/g, '\\|').replace(/\r?\n/g, '\\n');
  const index = [`# Module index (${ref} → ${tgt})`, '', `Generated by \`tools/hub_pages.js\`. Notes: \`notes/<id>.md\`.`, '', '| Module | → ' + tgt + ' | Area | Role | Notes |', '|---|---|---|---|---|'];
  let notesCount = 0;
  for (const r of A.modules) {
    const m = X.map[String(r.id)];
    const b = m ? byB.get(m.id) : null;
    const notesPath = path.join(notesDir, `${r.id}.md`);
    const notes = fs.existsSync(notesPath) ? fs.readFileSync(notesPath, 'utf8').trim() : null;
    if (notes) notesCount++;
    const lines = [
      `# Module ${r.id} (${ref}) → ${m ? m.id : 'no match'} (${tgt})`, '',
      `- **Factory:** F${r.factory} (${ref})${b ? `; F${b.factory} (${tgt})` : ''}`,
      `- **Match:** ${m ? `${m.method}, confidence ${m.confidence}` : 'none'}`,
      `- **Area:** ${r.area} (${r.area_by || ''})`,
      `- **Role:** ${r.role || '—'}`,
      `- **Size:** ${r.size} bytes, ${r.functions} functions; shape \`${r.shape}\``,
      '', '## Notes', '', notes || `_None yet. Add \`notes/${r.id}.md\`; it is inlined here on regeneration._`, '',
      '## Exports', '', r.exports.length ? '| Name | Kind | Detail |\n|---|---|---|\n' + r.exports.map(e =>
        `| \`${esc(e.name)}\` | ${esc(e.kind)} | ${[e.from !== undefined ? 'from ' + link(e.from) : '', e.dll ? 'dll `' + e.dll + '`' : '', e.value !== undefined ? '`' + esc(JSON.stringify(e.value)).slice(0, 80) + '`' : '', e.fid ? 'F' + e.fid : ''].filter(Boolean).join(', ')} |`).join('\n') : '_none detected_',
      '', '## Requires', '', r.requires.length ? r.requires.map(link).join(', ') : '_none_',
      ...(r.lazy_requires ? ['', 'Lazy (`import()`): ' + r.lazy_requires.map(link).join(', ')] : []),
      '', '## Uses (property paths read on required modules)', '',
      Object.keys(r.uses).length ? Object.entries(r.uses).map(([id, ps]) => `- ${link(id)}: ${ps.map(p => '`' + p + '`').join(', ')}`).join('\n') : '_none_',
      '', '## Importers', '', (importers.get(r.id) || []).map(link).join(', ') || '_none (entry, lazy, or dead)_',
      '', '## Distinctive strings', '', r.strings.length ? r.strings.map(s => '`' + esc(s).slice(0, 100) + '`').join(' · ') : '_none_', '',
    ];
    fs.writeFileSync(path.join(outDir, `${r.id}.md`), lines.join('\n'));
    index.push(`| ${link(r.id)} | ${m ? m.id : '—'} | ${r.area} | ${esc((r.role || '').slice(0, 70))} | ${notes ? 'yes' : ''} |`);
  }
  fs.writeFileSync(path.join(outDir, 'INDEX.md'), index.join('\n') + '\n');
  console.log(`wrote ${A.modules.length} pages to ${outDir} (${notesCount} with notes)`);
}

if (require.main === module) main();
